const lower = (s) => s.charAt(0).toLocaleLowerCase('ru') + s.slice(1);
export function skillCopy(entry, actions) {
  const custom = overrides[entry.name];
  let description = custom?.[0] ?? actions[entry.name] ?? entry.description;
  for (const [pattern, replacement] of glossary)
    description = description.replace(pattern, replacement);
  const action = description.replace(/\.$/, '');
  const criterion = custom?.[1] ?? `В текущей задаче нужно ${lower(action)}.`;
  return {
    ...entry,
    description,
    autoCriteria: entry.bundled && entry.automatic ? [criterion] : [],
    requestExample:
      custom?.[2] ??
      (entry.example && !/^Примени \$/.test(entry.example) ? entry.example : `${action}.`),
  };
}
