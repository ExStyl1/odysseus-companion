/**
 * P3.349 · the Claude hook roster, DERIVED rather than retyped.
 *
 * `scripts/claude-doc-anchors.tsv` is the offline snapshot of every section
 * anchor the cited Claude pages publish (regenerated by
 * `bun scripts/check-doc-anchors.ts --refresh`). On the `hooks` page every event
 * section publishes exactly one `<event>-input` sibling, and nothing else on the
 * page ends in `-input`, so those slugs ARE the roster. Measured 2026-09-04
 * against `curl -sL https://code.claude.com/docs/en/hooks.md`: 33 `### ` event
 * sections under §"Hook events", 33 `-input` slugs here, same names both ways.
 *
 * The names come back lowercase because an anchor is a slug; the comparisons
 * below are therefore case-folded, which is also what makes a rename visible —
 * a renamed event changes the slug, not just its capitalisation.
 */
function documentedClaudeHookEventSlugs(): string[] {
  // A missing or moved snapshot must THROW. Returning an empty roster would make
  // every assertion below vacuously true, which is the exact defect this test
  // was rewritten to remove.
  const tsv = readFileSync(CLAUDE_DOC_ANCHORS_TSV, 'utf-8');
  const slugs = tsv.split('\n')
    .filter(line => line && !line.startsWith('#'))
    .map(line => line.split('\t'))
    .filter(([page, anchor]) => page === 'hooks' && anchor?.endsWith('-input'))
    .map(([, anchor]) => anchor!.slice(0, -'-input'.length));
  return Array.from(new Set(slugs)).sort();
}

