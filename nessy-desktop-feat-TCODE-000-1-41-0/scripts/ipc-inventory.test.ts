/**
 * The enforcing reader for `ipc-inventory.ts`.
 *
 * `bun run ipc:inventory:check` sat only inside `bun run validate:ci`, and CI
 * runs `typecheck:all`, `lint`, `bun test` and `test:shared:all` — never that
 * aggregate, which additionally aborts at `test:doc-tools` before reaching it.
 * So the channel inventory went stale on the target tip by two entries and the
 * only thing that noticed was the frozen list's own `bun test`, whose failure
 * names no remedy. This file is the reader that does: `bun test` is what CI
 * runs, so a check wired anywhere else has none.
 *
 * It asserts the live artifact is sound AND that the audit can go red on every
 * defect class it claims to catch — a guard that cannot fail is
 * indistinguishable from no guard. The marker case matters most: it is the one
 * class with no other reader at all, because damaging the BEGIN/END pair leaves
 * the frozen list passing while the generator that maintains it cannot run.
 */

import { describe, expect, it } from 'bun:test'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

import { NOTICE, auditInventory, discardedLines, flattenValues, renderBlock } from './ipc-inventory.ts'
import { RPC_CHANNELS } from '../apps/electron/src/shared/types.ts'

const TEST_FILE = join(import.meta.dir, '..', 'apps', 'electron', 'src', 'shared', '__tests__', 'ipc-channels.test.ts')

/** The smallest file the generator can operate on, so a fixture is not a fake. */
function fixture(channels: readonly string[]): string {
  return `header\n${renderBlock([...channels].sort())}\nfooter\n`
}

describe('ipc-inventory', () => {
  it('the frozen channel list matches RPC_CHANNELS as committed', () => {
    const channels = flattenValues(RPC_CHANNELS as unknown as Record<string, unknown>)
    const audit = auditInventory(readFileSync(TEST_FILE, 'utf8'), channels)

    expect(audit.duplicates).toEqual([])
    expect(audit.markers).toBe('ok')
    // The assertion this file exists for. When it reds, run `bun run ipc:inventory`
    // and commit the block in the same commit as the channel change.
    expect(audit.stale).toBe(false)

    // Positive control: the walk really found the declaration rather than an
    // empty object, which would make every assertion above vacuously true.
    expect(channels.length).toBeGreaterThan(300)
    expect(channels).toContain('workspace:importClaudePreview')
  })

  it('reports a block that is missing a declared channel', () => {
    const audit = auditInventory(fixture(['a:one', 'a:two']), ['a:one', 'a:two', 'a:three'])
    expect(audit.stale).toBe(true)
    expect(audit.markers).toBe('ok')
    // The remedy is the rewritten file, and it must be complete rather than
    // merely different: this is the substitution the real drift needed.
    expect(auditInventory(audit.next as string, ['a:one', 'a:two', 'a:three']).stale).toBe(false)
  })

  it('reports a block whose channel was renamed, not only one that grew', () => {
    // A rename is the drift class the inventory exists for — same count, so a
    // length comparison alone would pass it.
    const audit = auditInventory(fixture(['a:one', 'a:two']), ['a:one', 'a:renamed'])
    expect(audit.stale).toBe(true)
  })

  it('accepts a block that already agrees, and is idempotent', () => {
    const audit = auditInventory(fixture(['a:one', 'a:two']), ['a:two', 'a:one'])
    expect(audit.stale).toBe(false)
    expect(audit.next).toBe(fixture(['a:one', 'a:two']))
  })

  it('reports missing markers — the class with no other reader', () => {
    const intact = fixture(['a:one'])
    const noBegin = intact.replace('// Auto-generated by scripts/ipc-inventory.ts — DO NOT edit by hand.\n', '')
    const noEnd = intact.replace('\n// End auto-generated', '')

    expect(noBegin).not.toBe(intact)
    expect(noEnd).not.toBe(intact)
    expect(auditInventory(noBegin, ['a:one']).markers).toBe('missing')
    expect(auditInventory(noEnd, ['a:one']).markers).toBe('missing')
    // A file with no markers is not "up to date": the generator cannot run, and
    // saying nothing here is how the block stopped being maintained.
    expect(auditInventory(noBegin, ['a:one']).next).toBeUndefined()
  })

  it('reports markers in the wrong order rather than slicing garbage', () => {
    const swapped = ['header', '// End auto-generated', '// Auto-generated by scripts/ipc-inventory.ts — DO NOT edit by hand.', 'footer'].join('\n')
    expect(auditInventory(swapped, ['a:one']).markers).toBe('out-of-order')
  })

  it('reports a duplicate wire name instead of deduping it into a pass', () => {
    const audit = auditInventory(fixture(['a:one']), ['a:one', 'a:one'])
    expect(audit.duplicates).toEqual(['a:one'])
    // Duplicates outrank staleness: two declarations answering to one wire name
    // must not be resolved by rewriting the block around them.
    expect(audit.stale).toBe(false)
    expect(audit.next).toBeUndefined()
  })

  it('writes the block sorted, because the frozen list is compared in order', () => {
    // `renderBlock` preserves the order it is handed; sorting is the audit's job,
    // and the frozen list is compared with `toEqual`, so order is part of the
    // contract rather than cosmetic.
    const audit = auditInventory(fixture(['a:one']), ['b:two', 'a:one'])
    const emitted = (audit.next as string).split('\n').filter(line => line.startsWith('  \''))
    expect(emitted).toEqual(["  'a:one',", "  'b:two',"])
  })
})

/**
 * P6.687 — what happens to a hand-written line inside the generated block.
 *
 * The block's first marker says «DO NOT edit by hand». It does not say that an
 * edit is DELETED, and it is: the block is re-rendered whole from `RPC_CHANNELS`,
 * so a comment written between the markers disappears on the next run with no
 * output of any kind. One was written and is gone, which is how the row was born.
 *
 * The row allowed two answers — preserve the comments, or say they are discarded
 * and count them. The second is what shipped, under the standing rule to write as
 * little code as possible: a comment inside a sorted, wholly re-rendered list has
 * no stable anchor to be re-attached to.
 */
describe('ipc-inventory — hand edits inside the block (P6.687)', () => {
  const withComment = (channels: readonly string[], comment: string): string =>
    fixture(channels).replace("const EXPECTED_CHANNELS", `${comment}\nconst EXPECTED_CHANNELS`)

  it('states at the head of the block that hand edits are discarded', () => {
    // The line the reader meets BEFORE editing, and it is the generator's own
    // output rather than a comment someone has to remember to keep.
    const lines = renderBlock(['a:one']).split('\n')
    expect(lines[1]).toBe(NOTICE)
    expect(NOTICE).toContain('discarded')
  })

  it('reports a hand-written comment as discarded, by its text', () => {
    const source = withComment(['a:one', 'a:two'], '  // kept the ordering deliberately, see P0.0')
    const audit = auditInventory(source, ['a:one', 'a:two'])

    expect(audit.discarded).toEqual(['  // kept the ordering deliberately, see P0.0'])
    // And the rewrite really does delete it — the count is a warning about
    // something that happens, not a hypothetical.
    expect(audit.next as string).not.toContain('kept the ordering deliberately')
    expect(discardedLines(audit.next as string)).toEqual([])
  })

  it('does NOT report a removed channel as a lost hand edit', () => {
    // The discrimination the row turns on. Diffing the old block against the new
    // one would call this line a discarded hand edit; it is a channel that left
    // the declaration, which is a different event with a different remedy.
    const source = fixture(['a:one', 'a:two'])
    const audit = auditInventory(source, ['a:one'])

    expect(audit.stale).toBe(true)
    expect(audit.discarded).toEqual([])
    expect(audit.next as string).not.toContain("'a:two'")
  })

  it('an older block is not STALE for want of the notice, but says it is missing', () => {
    // The transition, and the one judgement in this row: the frozen list is the
    // wire contract and `stale` is what says it drifted. Folding a comment into
    // that would turn a green gate red in every tree that had not regenerated
    // yet — including CI on a clean checkout — for a line of documentation.
    const older = fixture(['a:one', 'a:two']).replace(`${NOTICE}\n`, '')
    expect(older).not.toContain(NOTICE)

    const audit = auditInventory(older, ['a:one', 'a:two'])
    expect(audit.stale).toBe(false)
    expect(audit.noticeMissing).toBe(true)
    // …and the write it would perform adds it, so the notice lands on the next
    // run of the generator rather than on the next channel change.
    expect(audit.next as string).toContain(NOTICE)

    // Control: the same block WITH the notice reports neither.
    const current = auditInventory(fixture(['a:one', 'a:two']), ['a:one', 'a:two'])
    expect(current.stale).toBe(false)
    expect(current.noticeMissing).toBe(false)
  })

  it('the notice itself is never counted as a hand edit', () => {
    expect(discardedLines(fixture(['a:one']))).toEqual([])
  })
})
