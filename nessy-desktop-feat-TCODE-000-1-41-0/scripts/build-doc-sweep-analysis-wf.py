#!/usr/bin/env python3
"""Emit the phase-3 workflow: the two analytical sections plus the plan slicing.

Everything countable is generated by build-doc-sweep-report.py. This phase only
produces what needs judgement: why the refuted findings were wrong grouped by
KIND of mistake, and how the survivors cut into implementation plans.

Usage: python3 scripts/build-doc-sweep-analysis-wf.py <output.js>
"""

import json
import os
import sys

REPO = "/Users/i.i.gavrikov/Desktop/work/nessy-desktop"
DATA = f"{REPO}/docs/superpowers/specs/data"
P2 = f"{DATA}/2026-07-31-doc-sweep-phase2.json"
SDIR = f"{DATA}/phase25-specs"
OUT = f"{DATA}/phase3-analysis.json"

UNITS_SCHEMA = {
    "type": "object",
    "required": ["units", "prose"],
    "properties": {
        "prose": {"type": "string"},
        "units": {
            "type": "array",
            "items": {
                "type": "object",
                "required": ["name", "title", "findings", "why", "dependsOn", "effort", "rationale"],
                "properties": {
                    "name": {"type": "string"},
                    "title": {"type": "string"},
                    "findings": {"type": "array", "items": {"type": "string"}},
                    "why": {"type": "string"},
                    "dependsOn": {"type": "array", "items": {"type": "string"}},
                    "effort": {"type": "string", "enum": ["S", "M", "L"]},
                    "rationale": {"type": "string"},
                },
            },
        },
    },
}


def main():
    out_path = sys.argv[1]
    p2 = json.load(open(P2))
    survived = [r for r in p2["results"] if not r["verdict"]["refuted"]]
    refuted = [r for r in p2["results"] if r["verdict"]["refuted"]]

    specs = {}
    if os.path.isdir(SDIR):
        for n in sorted(os.listdir(SDIR)):
            if n.endswith(".json"):
                try:
                    s = json.load(open(os.path.join(SDIR, n)))
                    specs[s.get("id") or n[:-5]] = s
                except json.JSONDecodeError:
                    pass

    work = [
        {
            "id": r["id"], "page": r["slug"], "severity": r["severity"],
            "kind": specs.get(r["id"], {}).get("kind", ""),
            "subsystem": specs.get(r["id"], {}).get("subsystem", ""),
            "divergence": specs.get(r["id"], {}).get("divergence", r["claim"]),
            "files": [c["file"] for c in specs.get(r["id"], {}).get("change", [])],
            "blastRadius": specs.get(r["id"], {}).get("blastRadius", ""),
            "userImpact": specs.get(r["id"], {}).get("userImpact", ""),
            "effort": specs.get(r["id"], {}).get("effort", ""),
        }
        for r in survived
    ]
    kills = [{"page": r["slug"], "claim": r["claim"], "why": r["verdict"]["why"]} for r in refuted]

    script = """export const meta = {
  name: 'claude-doc-sweep-phase3',
  description: 'Refutation taxonomy and the plan slicing for the doc sweep report',
  phases: [{ title: 'Analyse', detail: 'taxonomy of what was wrong, and how the survivors cut into plans' }],
}

const OUT = %(out)s
const REPO = %(repo)s
const N_WORK = %(nwork)d
const N_KILLS = %(nkills)d
const UNITS_SCHEMA = %(schema)s

phase('Analyse')

const [taxonomy, slicing] = await parallel([
  () => agent(
    `${N_KILLS} findings from a full read of Claude Code's documentation against the fork at ${REPO} were each handed to an adversarial challenger, and the challenger killed them. Read them, then group them by the KIND of mistake, not page by page, so the next sweep avoids the kind rather than the instance.

  cd ${REPO} && python3 scripts/doc-sweep-extract.py refuted

The kinds this repo has already paid for, as a starting vocabulary — extend it, do not force findings into it:
- a fabricated quote: the sentence is not on the page at all
- a quote cut at the load-bearing point, where the second half reverses the conclusion
- the identifier really is unwired, but the CONSEQUENCE is false because something upstream already handled it
- the wrong subsystem: an identically-named symbol lives in a sibling, and the behaviour was read off the sibling
- a recorded owner decision with a reason, read as a defect
- a deliberate product difference: dropped subscription flows, corporate gateway, the rename

For each kind: name it, say how many findings it took, give two or three of the sharpest instances with page and one line of why, and state the CHECK that would have caught the kind up front. Write RUSSIAN prose, keep identifiers, paths and doc quotes verbatim English. Markdown, no top-level heading — this is spliced under one. Do not pad and do not restate the table that follows this section.`,
    { label: 'taxonomy', phase: 'Analyse' },
  ),
  () => agent(
    `${N_WORK} divergences between Claude Code's documentation and the fork at ${REPO} survived adversarial challenge, each already read back off the code and classified. Load them, then cut them into implementation plans.

  cd ${REPO} && python3 scripts/doc-sweep-extract.py worklist

The repo's plan convention: one plan per coherent contract, living in docs/superpowers/plans/, each carrying a Tracker section with one row per task. A plan is worth cutting when its findings share a contract, a file set or a wire boundary — not merely a subsystem name. Read ${REPO}/docs/superpowers/specs/2026-07-25-nessy-claude-parity-audit.md section A to see how existing units are shaped and numbered, and ${REPO}/AGENTS.md for what counts as a risk trigger.

Return:
- units: the proposed plans. \\`name\\` is a short kebab-case slug that could become the plan filename. \\`findings\\` lists the finding ids it owns — every id in the input must appear in exactly one unit. \\`why\\` says what binds them into one plan. \\`dependsOn\\` names other unit slugs that must land first, and is empty when there is none — order by dependency, not by size. \\`rationale\\` says what a user gets when it lands, concretely.
- prose: a short ordered walkthrough of the units in execution order, saying WHY that order. Name the one or two that change how the others must be written — those lead. RUSSIAN prose, identifiers and paths verbatim English. Markdown, no top-level heading.

A unit that crosses a persistence or wire boundary must say so in its rationale; that is a risk trigger in this repo and it changes how the plan is written.`,
    { label: 'slicing', phase: 'Analyse', schema: UNITS_SCHEMA },
  ),
])

const payload = { taxonomy, plan: slicing && slicing.prose, units: (slicing && slicing.units) || [] }

await agent(
  `Persist this analysis verbatim to ${OUT}. Write the JSON exactly as given, changing nothing:

\\`\\`\\`json
${JSON.stringify(payload)}
\\`\\`\\`

Use a quoted heredoc so the shell cannot touch it, then verify with \\`python3 -m json.tool ${OUT}\\`. Return only the word OK.`,
  { label: 'persist', phase: 'Analyse' },
)

return { units: payload.units.length, covered: payload.units.reduce((n, u) => n + u.findings.length, 0), of: N_WORK }
""" % {
        "out": json.dumps(OUT),
        "repo": json.dumps(REPO),
        "nwork": len(work),
        "nkills": len(kills),
        "schema": json.dumps(UNITS_SCHEMA),
    }

    open(out_path, "w").write(script)
    print(f"survivors {len(work)} | refuted {len(kills)} | wrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
