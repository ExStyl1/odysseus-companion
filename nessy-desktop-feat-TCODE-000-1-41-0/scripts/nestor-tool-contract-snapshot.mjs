#!/usr/bin/env node
/**
 * Snapshot the Nestor backend's builtin tool contract into a committed fixture.
 *
 * The backend declares every builtin in ONE file — `tools.go` — as `chat.Tool`
 * literals with `Strict: true`, so the JSON-Schema `properties` / `required` sets
 * there are the complete, closed vocabulary the model can ever send us. This
 * generator transcribes those sets mechanically (no hand-copying) into
 * `packages/shared/src/agent/backend/nestor-cloud/__tests__/fixtures/backend-tool-contract.json`,
 * which `__tests__/tool-contract-snapshot.test.ts` then drives `tool-schema.ts`
 * from.
 *
 * IMPORTANT — the fixture is the UNION across agent modes. This generator reads
 * `tools.go` alone and CANNOT see the mode/flag split that decides which subset is
 * actually offered on a given turn (`codeagent/agent.go:70-92`):
 *   - `write_to_file` / `replace_in_file` are appended only in ACT mode;
 *   - `plan_mode_respond` only in the default (PLAN) branch;
 *   - `activate_skill` only while the `a2a_skills_enabled` flag is on (default on).
 * A tool being in this snapshot therefore means "the backend can define it", never
 * "the backend offers it on every turn".
 *
 * `.references/` is gitignored, so this runs only on a machine with the pinned
 * backend checkout; the committed fixture is the contract of record everywhere else.
 *
 * Usage:
 *   node scripts/nestor-tool-contract-snapshot.mjs            # write the fixture
 *   node scripts/nestor-tool-contract-snapshot.mjs --check     # verify, exit 1 on drift
 *   node scripts/nestor-tool-contract-snapshot.mjs --stdout    # print, write nothing
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Backend checkout the contract was transcribed from; bump deliberately, never per run. */
const SOURCE_PIN = 'df526b7';
const SOURCE_REPO = '.references/nestor-code-completion';
const SOURCE_FILE = 'service/nestor/internal/usecase/vibe/agent/codeagent/tools.go';
const SOURCE_PATH = join(SOURCE_REPO, SOURCE_FILE);
const FIXTURE_PATH = join(
  'packages', 'shared', 'src', 'agent', 'backend', 'nestor-cloud',
  '__tests__', 'fixtures', 'backend-tool-contract.json',
);

const NOTE = 'GENERATED by scripts/nestor-tool-contract-snapshot.mjs — do not hand-edit. '
  + 'The tool list is the UNION across agent modes: the generator reads tools.go only and cannot see the '
  + 'ACT/PLAN/flag split at codeagent/agent.go:70-92, where write_to_file and replace_in_file are ACT-only, '
  + 'plan_mode_respond is PLAN-only, and activate_skill rides the a2a_skills_enabled flag (default on). '
  + 'Every definition is Strict:true, which is what makes each property set closed.';

/**
 * Go source carries the tool DESCRIPTIONS as raw backtick strings and interpreted
 * string literals containing arbitrary prose (SEARCH/REPLACE markers, examples, …).
 * Strip those before any brace counting, or one `{` in a description silently
 * re-nests the whole parse.
 */
function stripDocumentation(source) {
  return source
    .replace(/`[^`]*`/g, '""')
    .replace(/"description":\s*"(?:[^"\\]|\\.)*"/g, '"description": ""');
}

/** Body of the `{ … }` whose opening brace sits at `open`. */
function balancedBody(text, open) {
  let depth = 0;
  for (let i = open; i < text.length; i += 1) {
    const ch = text[i];
    if (ch === '{') depth += 1;
    else if (ch === '}') {
      depth -= 1;
      if (depth === 0) return text.slice(open + 1, i);
    }
  }
  throw new Error(`Unbalanced braces starting at offset ${open}`);
}

/** `"<key>": map[string]any{ … }` entries at the TOP level of `block` only. */
function topLevelObjects(block) {
  const entries = [];
  const pattern = /"([A-Za-z_][A-Za-z0-9_]*)":\s*map\[string\]any\{/g;
  let cursor = 0;
  for (;;) {
    pattern.lastIndex = cursor;
    const match = pattern.exec(block);
    if (!match) return entries;
    const open = match.index + match[0].length - 1;
    const body = balancedBody(block, open);
    entries.push({ key: match[1], body });
    cursor = open + body.length + 2;
  }
}

function objectBody(block, key) {
  const marker = new RegExp(`"${key}":\\s*map\\[string\\]any\\{`);
  const match = marker.exec(block);
  if (!match) return null;
  return balancedBody(block, match.index + match[0].length - 1);
}

function stringLiteral(block, key) {
  const match = new RegExp(`"${key}":\\s*"([^"]*)"`).exec(block);
  return match ? match[1] : null;
}

function numberLiteral(block, key) {
  const match = new RegExp(`"${key}":\\s*(-?\\d+)`).exec(block);
  return match ? Number(match[1]) : null;
}

function goStringSlice(block, key) {
  const match = new RegExp(`"${key}":\\s*\\[\\]string\\{([^}]*)\\}`).exec(block);
  if (!match) return [];
  return [...match[1].matchAll(/"([^"]*)"/g)].map(entry => entry[1]);
}

function parseProperty(name, body) {
  const type = stringLiteral(body, 'type');
  if (!type) throw new Error(`Property ${name} has no "type"`);
  const property = { type };

  const items = objectBody(body, 'items');
  if (items) {
    const itemType = stringLiteral(items, 'type');
    if (!itemType) throw new Error(`Property ${name} has "items" without a "type"`);
    property.items = { type: itemType };
  }
  const minItems = numberLiteral(body, 'minItems');
  if (minItems !== null) property.minItems = minItems;
  const maxItems = numberLiteral(body, 'maxItems');
  if (maxItems !== null) property.maxItems = maxItems;

  return property;
}

function parseTools(source) {
  const stripped = stripDocumentation(source);
  const names = [...stripped.matchAll(/Name:\s*"([A-Za-z_][A-Za-z0-9_]*)"/g)];
  if (names.length === 0) throw new Error('No tool definitions found — did tools.go move or change shape?');

  return names.map((match, index) => {
    const end = index + 1 < names.length ? names[index + 1].index : stripped.length;
    const block = stripped.slice(match.index, end);
    const name = match[1];

    const parameters = parametersBody(block, name);
    const schemaType = stringLiteral(parameters, 'type');
    if (schemaType !== 'object') throw new Error(`${name}: expected a "type":"object" schema, got ${schemaType}`);

    const propertiesBlock = objectBody(parameters, 'properties');
    if (propertiesBlock === null) throw new Error(`${name}: no "properties" block`);

    const properties = {};
    for (const entry of topLevelObjects(propertiesBlock)) {
      properties[entry.key] = parseProperty(`${name}.${entry.key}`, entry.body);
    }

    const required = goStringSlice(parameters, 'required');
    for (const key of required) {
      if (!(key in properties)) throw new Error(`${name}: required key "${key}" is not a declared property`);
    }

    return { name, strict: /Strict:\s*true/.test(block), required, properties };
  });
}

/** `Parameters: map[string]any{ … }` is a Go FIELD, not a quoted key. */
function parametersBody(block, name) {
  const match = /Parameters:\s*map\[string\]any\{/.exec(block);
  if (!match) throw new Error(`${name}: no Parameters block`);
  return balancedBody(block, match.index + match[0].length - 1);
}

function build() {
  const absolute = join(ROOT, SOURCE_PATH);
  if (!existsSync(absolute)) {
    throw new Error(
      `Backend source not found at ${SOURCE_PATH}. This generator needs the pinned checkout `
      + `(${SOURCE_REPO} @ ${SOURCE_PIN}); .references/ is gitignored, so the committed fixture is `
      + 'the contract of record without it.',
    );
  }

  return `${JSON.stringify({
    note: NOTE,
    generator: 'scripts/nestor-tool-contract-snapshot.mjs',
    source: join(SOURCE_REPO, SOURCE_FILE),
    sourceCommit: SOURCE_PIN,
    tools: parseTools(readFileSync(absolute, 'utf8')),
  }, null, 2)}\n`;
}

/** Compact positional line diff — the whole file twice is unreadable in a test failure. */
function lineDiff(committed, generated, limit = 40) {
  if (committed === null) return '(the fixture file is missing entirely)';
  const before = committed.split('\n');
  const after = generated.split('\n');
  const lines = [];
  for (let i = 0; i < Math.max(before.length, after.length); i += 1) {
    if (before[i] === after[i]) continue;
    if (lines.length >= limit) {
      lines.push('  … (more differences suppressed)');
      break;
    }
    if (before[i] !== undefined) lines.push(`- ${i + 1}: ${before[i]}`);
    if (after[i] !== undefined) lines.push(`+ ${i + 1}: ${after[i]}`);
  }
  return lines.join('\n');
}

function main() {
  const args = new Set(process.argv.slice(2));
  const generated = build();
  const fixture = join(ROOT, FIXTURE_PATH);

  if (args.has('--stdout')) {
    process.stdout.write(generated);
    return;
  }

  if (args.has('--check')) {
    const current = existsSync(fixture) ? readFileSync(fixture, 'utf8') : null;
    if (current === generated) {
      process.stdout.write(`${FIXTURE_PATH} is up to date with ${SOURCE_FILE} @ ${SOURCE_PIN}\n`);
      return;
    }
    process.stderr.write(
      `${FIXTURE_PATH} is STALE against ${SOURCE_PATH} @ ${SOURCE_PIN}.\n`
      + 'Re-run: node scripts/nestor-tool-contract-snapshot.mjs\n\n'
      + `${lineDiff(current, generated)}\n`,
    );
    process.exitCode = 1;
    return;
  }

  writeFileSync(fixture, generated);
  process.stdout.write(`Wrote ${FIXTURE_PATH}\n`);
}

main();
