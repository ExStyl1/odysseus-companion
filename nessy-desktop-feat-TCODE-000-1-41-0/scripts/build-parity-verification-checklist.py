#!/usr/bin/env python3
"""Build the live-verification checklist for the doc-sweep parity wave.

One check per finding, worded from what a USER does and sees, because that is what
a live pass can actually falsify. The source is each finding's `userImpact` — the
field the classifiers were told to fill with "which action, which surface, what
they see or fail to see", and to write "none observable" rather than guess.

That split is the point of this file: a finding whose impact is latent CANNOT be
confirmed by clicking, and listing it as a live case would produce a pass that
means nothing. Those are routed to their unit's tests instead, and the checklist
says so per row rather than silently mixing them.

Regenerate after any tracker or spec change:
  python3 scripts/build-parity-verification-checklist.py
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
DATA = os.path.join(ROOT, "docs", "superpowers", "specs", "data")
PLAN = os.path.join(ROOT, "docs", "superpowers", "plans", "2026-08-04-doc-sweep-parity-wave.md")
OUT = os.path.join(ROOT, "docs", "testing", "parity-wave-verification-checklist.md")

P2 = os.path.join(DATA, "2026-07-31-doc-sweep-phase2.json")
SDIR = os.path.join(DATA, "phase25-specs")
ANALYSIS = os.path.join(DATA, "phase3-analysis.json")

LATENT = re.compile(r"^\s*(none observable|not observable|latent)", re.I)


def clip(s, n):
    s = " ".join(str(s or "").split()).replace("|", "/")
    return s if len(s) <= n else s[: n - 1] + "…"


def main():
    results = {r["id"]: r for r in json.load(open(P2))["results"]}
    specs = {}
    for n in sorted(os.listdir(SDIR)):
        if n.endswith(".json"):
            s = json.load(open(os.path.join(SDIR, n)))
            specs[s.get("id") or n[:-5]] = s

    units = json.load(open(ANALYSIS))["units"]
    by = {u["name"]: u for u in units}
    done, order, rem = set(), [], list(units)
    while rem:
        ready = [u for u in rem if all(d in done or d not in by for d in u.get("dependsOn", []))]
        if not ready:
            order += rem
            break
        for u in ready:
            order.append(u)
            done.add(u["name"])
        rem = [u for u in rem if u["name"] not in done]
    R = {u["name"]: f"R{31+i}" for i, u in enumerate(order)}

    deferred = set()
    plan = open(PLAN).read()
    for name in by:
        if re.search(r"^\|\s*" + re.escape(R[name]) + r"\s*\|.*⏸", plan, re.M):
            deferred.add(name)

    live = latent = 0
    o = []
    w = o.append
    w("# Parity wave — live verification checklist")
    w("")
    w("Generated by `scripts/build-parity-verification-checklist.py` from each finding's")
    w("recorded user impact. Do not hand-edit — add findings to the specs and regenerate.")
    w("")
    w("Units and order come from `docs/superpowers/plans/2026-08-04-doc-sweep-parity-wave.md`;")
    w("the change list per finding is in")
    w("`docs/superpowers/specs/2026-08-02-claude-doc-sweep-worklist.md`.")
    w("")
    w("**Two kinds of row, and the difference decides what a pass means.**")
    w("")
    w("- 🖐 **live** — a user-visible behaviour. Drive it in a packaged build and observe.")
    w("  `electron:dev` runs the host and the Pi subprocess from BUILT bundles, and")
    w("  `resolveInterceptorBundlePath` silently starts Pi UNPATCHED when the bundle is")
    w("  missing, so a dev build can pass while the shipped artifact fails.")
    w("- 🧪 **latent** — the classifier recorded no observable impact. It CANNOT be")
    w("  confirmed by clicking; a green live pass here would be meaningless. Confirm it")
    w("  by the unit's own test, and record which test.")
    w("")
    w("Force dark theme before any screenshot. Driver: `scripts/cdp/`; product-indexed")
    w("cases live in `docs/testing/cdp-live-checklist.md` and a unit that adds a live")
    w("case there lands it in the same commit.")
    w("")

    for u in order:
        rid = R[u["name"]]
        rows = [(f, specs[f]) for f in u["findings"] if f in specs]
        mark = " ⏸ DEFERRED" if u["name"] in deferred else ""
        w(f"## {rid} · `{u['name']}`{mark}")
        w("")
        w(f"{clip(u['title'], 200)}")
        w("")
        if u["name"] in deferred:
            w("_Deferred by owner decision 2026-08-04 — not part of this wave's live pass._")
            w("")
        w("| ✓ | # | Kind | What to do and what must happen |")
        w("| --- | --- | --- | --- |")
        for fid, s in rows:
            impact = s.get("userImpact", "")
            if LATENT.match(impact):
                kind = "🧪 latent"
                latent += 1
            else:
                kind = "🖐 live"
                live += 1
            w(f"| ☐ | {fid} | {kind} | **`{results[fid]['slug']}`** — {clip(impact, 520)} |")
        w("")

    o.insert(4, f"**{live} live checks · {latent} latent checks · "
                f"{len(order)} units ({len(deferred)} deferred).**\n")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(o) + "\n")
    print(f"wrote {OUT}")
    print(f"units {len(order)} · deferred {len(deferred)} · live {live} · latent {latent}")


if __name__ == "__main__":
    main()
