import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';

const root = process.cwd();
const require = createRequire(path.join(root, 'package.json'));
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');

for (const file of ['package.json', 'packages/cli/package.json']) {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  assert.equal(manifest.config.sandboxImageUri, 'nessy-cli-sandbox', file);
}

function loadSource(relative) {
  const file = path.join(root, relative);
  const source = fs.readFileSync(file, 'utf8');
  const { outputText } = ts.transpileModule(source, {
    fileName: file,
    compilerOptions: {
      jsx: ts.JsxEmit.React,
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      esModuleInterop: true,
    },
  });
  const module = { exports: {} };
  vm.runInNewContext(
    `(function(require, module, exports) {${outputText}\n})`,
    {},
    { filename: file },
  )(createRequire(file), module, module.exports);
  return module.exports;
}

const models = loadSource(
  'packages/desktop/packages/shared/src/config/models.ts',
);
for (const id of ['qwen3-coder', 'qwen-max', 'QWEN_MAX']) {
  assert.equal(models.isNessyModel(id), true, id);
  assert.equal(models.getModelProvider(id), 'nessy', id);
}
assert.equal(models.isNessyModel('gpt-4o'), false);
assert.equal(models.getModelDisplayName('qwen-max'), 'Nessy max');

const { ShareCard } = loadSource(
  'packages/web-templates/src/insight/src/ShareCard.tsx',
);
for (const theme of ['light', 'dark']) {
  const html = renderToStaticMarkup(
    React.createElement(ShareCard, {
      theme,
      data: { heatmap: {}, totalMessages: 3, totalSessions: 1 },
    }),
  );
  assert.match(html, /Generated by Nessy CLI/);
  assert.match(html, /gitlab\.tcsbank\.ru\/nestor\/nessy-cli/);
  assert.doesNotMatch(html, /qwen/i);
}

const { build } = require('esbuild');
const { JSDOM, VirtualConsole } = require('jsdom');
for (const name of ['cdn-usage-demo.html', 'complex-chat-demo.html']) {
  const file = path.join(root, 'packages/webui/examples', name);
  const html = fs.readFileSync(file, 'utf8');
  assert.doesNotMatch(html, /qwen/i);
  const source = html.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1];
  assert.ok(source, `${name}: missing module script`);
  assert.match(source, /from '\.\.\/dist\/index\.js'/);
  assert.ok(fs.existsSync(path.join(path.dirname(file), '../dist/styles.css')));
  const bundle = await build({
    stdin: { contents: source, resolveDir: path.dirname(file) },
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'iife',
    define: { 'process.env.NODE_ENV': '"production"' },
  });
  const errors = [];
  const virtualConsole = new VirtualConsole();
  virtualConsole.on('jsdomError', (error) => errors.push(error.message));
  virtualConsole.on('error', (error) => errors.push(String(error)));
  const dom = new JSDOM(html, {
    runScripts: 'outside-only',
    pretendToBeVisual: true,
    virtualConsole,
  });
  try {
    // JSDOM has no layout or scrolling; execute the actual rendering code.
    dom.window.HTMLElement.prototype.scrollIntoView = () => {};
    dom.window.HTMLElement.prototype.scrollTo = () => {};
    dom.window.eval(bundle.outputFiles[0].text);
    const selector = name.startsWith('cdn-')
      ? '#chat-root-no-babel'
      : '#complex-chat-root';
    const rendered = () =>
      dom.window.document.querySelector(selector)?.textContent.trim();
    const deadline = Date.now() + 2_000;
    while (!rendered() && errors.length === 0 && Date.now() < deadline) {
      await new Promise((resolve) => setTimeout(resolve, 20));
    }
    assert.deepEqual(errors, [], name);
    assert.ok(rendered(), `${name}: empty chat`);
  } finally {
    dom.window.close();
  }
}
console.log(
  'Product checks passed: sandbox image, Desktop models, Insights card, browser examples.',
);
